// Makes the spike's own ES256 signing key, once.
// Private JWK -> .env.spike (git-ignored, never printed). Public JWKS -> site/.well-known/jwks.json (git-ignored, served by the draft deploy).
// The Neon Data API's public source accepts RS256 and ES256 and requires a `kid`, so ES256 with a kid.
import { generateKeyPair, exportJWK } from "jose";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { randomBytes } from "node:crypto";

const envFile = new URL("../.env.spike", import.meta.url);
const jwksFile = new URL("../site/.well-known/jwks.json", import.meta.url);
if (existsSync(envFile) && /^SPIKE_JWT_PRIVATE_JWK=.+/m.test(readFileSync(envFile, "utf8"))) {
  console.log("key already exists; not replaced");
  process.exit(0);
}
const { publicKey, privateKey } = await generateKeyPair("ES256", { extractable: true });
const kid = "spike-" + randomBytes(4).toString("hex");
const pub = { ...(await exportJWK(publicKey)), kid, alg: "ES256", use: "sig" };
const priv = { ...(await exportJWK(privateKey)), kid, alg: "ES256", use: "sig" };
const lines = [
  "# Generated by scripts/make-key.mjs. Git-ignored. Throwaway: deleted with the spike.",
  "SPIKE_JWT_PRIVATE_JWK=" + JSON.stringify(priv),
  "SPIKE_USER_PASSWORD=" + randomBytes(18).toString("base64url"),
  "BETTER_AUTH_SECRET=" + randomBytes(32).toString("base64url"),
  "",
];
writeFileSync(envFile, lines.join("\n"));
mkdirSync(new URL("../site/.well-known/", import.meta.url), { recursive: true });
writeFileSync(jwksFile, JSON.stringify({ keys: [pub] }, null, 2));
console.log("made key", kid, "and the public JWKS file");
